"""Explicit installation of only the tool-owned private VPS CONNECT service.

No SSH settings, firewall rules, VPN services, or Claude account stores are changed.
The local client sends these standard-library modules through verified SSH.
"""

from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .config import Config

MANAGED_HEADER = "# Generated by vps-route setup-vps\n"
SERVICE_NAME = "vps-route-connect.service"
SERVER_FILES = {"__init__.py", "remote.py", "wire.py"}


def private_directory(path: Path) -> None:
    for parent in (path, *path.parents):
        if parent.is_symlink():
            raise ValueError("managed_directory_must_not_be_symlinked")
    path.mkdir(parents=True, mode=0o700, exist_ok=True)
    if path.stat().st_uid != os.getuid():
        raise ValueError("managed_directory_must_be_owned")
    path.chmod(0o700)


def atomic_text(path: Path, content: str) -> None:
    if path.is_symlink():
        raise ValueError("managed_file_must_not_be_symlinked")
    descriptor, temporary = tempfile.mkstemp(prefix=".vps-route-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def service_text(server_root: Path, socket_path: Path, *, system: bool = False) -> str:
    def value(path: Path) -> str:
        value = str(path)
        if any(ord(char) < 32 for char in value):
            raise ValueError("invalid_service_path")
        return value.replace("%", "%%")

    # ExecStart parses quoted arguments; WorkingDirectory takes a literal path.
    def quote(path: Path) -> str:
        return '"' + value(path).replace("\\", "\\\\").replace('"', '\\"') + '"'

    return (
        MANAGED_HEADER + "[Unit]\nDescription=VPS Route private HTTPS CONNECT service\n"
        "After=network.target\n\n[Service]\nType=simple\n"
        f"WorkingDirectory={value(server_root)}\n"
        f"ExecStart=/usr/bin/python3 -m claude_launcher.remote --socket {quote(socket_path)}\n"
        "Restart=on-failure\nRestartSec=3\nUMask=0077\nNoNewPrivileges=yes\n"
        f"\n[Install]\nWantedBy={'multi-user.target' if system else 'default.target'}\n"
    )


def apply_server(payload: dict, *, home: Path | None = None,
                 unit_directory: Path | None = None, system: bool | None = None) -> dict:
    home = Path.home().resolve() if home is None else home.resolve()
    socket_path = Path(payload["remote_socket"])
    if (not socket_path.is_absolute() or ".." in socket_path.parts
            or not socket_path.is_relative_to(home) or socket_path.parent == home):
        raise ValueError("remote_socket_must_be_in_a_private_directory_under_ssh_user_home")
    files = payload["files"]
    if set(files) != SERVER_FILES or not all(isinstance(value, str) for value in files.values()):
        raise ValueError("unexpected_server_files")
    if system is None:
        system = os.getuid() == 0
    units = unit_directory or (Path("/etc/systemd/system") if system
                               else home / ".config/systemd/user")
    for parent in (units, *units.parents):
        if parent.is_symlink():
            raise ValueError("unit_directory_must_not_be_symlinked")
    unit = units / SERVICE_NAME
    if unit.is_symlink() or (unit.exists() and not unit.read_text().startswith(MANAGED_HEADER)):
        raise ValueError("refusing_to_replace_unmanaged_service")
    server_root = home / ".local/share/claude-launcher/server"
    package = server_root / "claude_launcher"
    if server_root.exists() and not (server_root / ".vps-route-managed").is_file():
        raise ValueError("refusing_to_replace_unmanaged_server_directory")
    if (socket_path.exists() or socket_path.is_symlink()) and not (
        unit.exists() and (server_root / ".vps-route-managed").is_file()
    ):
        raise ValueError("refusing_to_take_over_existing_socket; use_existing_service_instead")
    private_directory(socket_path.parent)
    private_directory(server_root)
    private_directory(package)
    units.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        atomic_text(package / name, content)
    atomic_text(server_root / ".vps-route-managed", "vps-route private CONNECT server\n")
    atomic_text(unit, service_text(server_root, socket_path, system=system))
    manager = ["systemctl", *([] if system else ["--user"])]
    # Only this owned service is enabled/restarted. Missing user bus fails closed.
    for operation in (["daemon-reload"], ["enable", SERVICE_NAME],
                      ["restart", SERVICE_NAME], ["is-active", "--quiet", SERVICE_NAME]):
        subprocess.run([*manager, *operation], check=True, timeout=20,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return {"service": SERVICE_NAME, "scope": "system" if system else "user",
            "socket": str(socket_path), "account_files_read": False,
            "ssh_or_firewall_changed": False}


def remote_main() -> int:
    try:
        payload = json.load(sys.stdin)
        if sys.version_info < (3, 10):
            raise ValueError("system_python_3_10_required")
        result = apply_server(payload)
        print(json.dumps(result))
        return 0
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError):
        print("vps-route: server_setup_failed; inspect_systemd_and_managed_paths",
              file=sys.stderr)
        return 69


def deploy_server(config: Config) -> int:
    from .runner import ssh_arguments

    package = Path(__file__).resolve().parent
    payload = {"remote_socket": config.remote_socket,
               "files": {name: (package / name).read_text() for name in SERVER_FILES}}
    bootstrap = Path(__file__).read_text() + "\nraise SystemExit(remote_main())\n"
    remote_command = shlex.join(["/usr/bin/python3", "-c", bootstrap])
    command = [*ssh_arguments(config), config.ssh_host, remote_command]
    try:
        result = subprocess.run(command, input=json.dumps(payload), text=True,
                                timeout=100, check=False)
    except subprocess.TimeoutExpired:
        print("vps-route: VPS setup timed out; verify service state before retrying")
        return 69
    if result.returncode:
        print("vps-route: VPS setup did not complete; no direct-route fallback")
        return 69
    return 0
